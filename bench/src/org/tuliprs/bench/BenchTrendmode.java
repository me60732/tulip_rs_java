package org.tuliprs.bench;

import org.tuliprs.Outcome;
import org.tuliprs.Result;
import org.tuliprs.SimdResult;
import org.tuliprs.State;
import org.tuliprs.indicators.Trendmode;

/**
 * Trendmode — tulip_rs_java benchmark.
 * No ta4j counterpart: Ehlers indicators (supersmoother, trendmode) are not in ta4j 0.19.
 */
public final class BenchTrendmode implements BenchProvider {

    @Override
    public Benchmark def() {
        return Benchmark.builder("trendmode")
                .options(new double[][]{{0.0}, {0.05}, {0.07}, {0.10}}) // matches Go/Python
                .tulip((s, o) -> {
                    Outcome oc = Trendmode.indicator(new double[][]{s.close}, o);
                    try (Result res = oc.result(); State st = oc.state()) {
                        if (res.numOutputs() > 0 && res.rowLength(0) > 0) {
                            Harness.consume(res.get(0, 0));
                        }
                    }
                })
                .simdAssets((stocks, o) -> {
                    double[][][] assets = new double[stocks.length][][];
                    for (int i = 0; i < stocks.length; i++) {
                        assets[i] = new double[][]{stocks[i].close};
                    }
                    try (SimdResult sim = Trendmode.simdByAssets(assets, o)) {
                        if (sim.rowLength(0, 0) > 0) {
                            Harness.consume(sim.get(0, 0, 0));
                        }
                    }
                })
                .simdOptions((s, optSets) -> {
                    try (SimdResult sim = Trendmode.simdByOptions(new double[][]{s.close}, optSets)) {
                        if (sim.rowLength(0, 0) > 0) {
                            Harness.consume(sim.get(0, 0, 0));
                        }
                    }
                })
                .build();
    }
}
